async function seed() {
  console.log("[seed-qna] 시작");
  const now = nowTimestamp();

  // 1) 기존 Q&A 시드 제거 — 스크립트 재실행 안전성 확보
  sqlite.prepare("DELETE FROM qna_questions").run();
  sqlite.prepare("DELETE FROM qna_categories").run();

  // 2) 카테고리 트리 생성
  const slugToId = new Map();
  let topOrder = 0;
  for (const top of CATEGORY_TREE) {
    const [topRow] = await db.insert(qnaCategories).values({
      name: top.name, slug: top.slug, parentId: null, depth: 0,
      description: top.description, sortOrder: topOrder++, isActive: 1,
    }).returning();
    slugToId.set(top.slug, topRow.id);

    let midOrder = 0;
    for (const mid of top.children) {
      const [midRow] = await db.insert(qnaCategories).values({
        name: mid.name, slug: mid.slug, parentId: topRow.id, depth: 1,
        description: mid.description, sortOrder: midOrder++, isActive: 1,
      }).returning();
      slugToId.set(mid.slug, midRow.id);

      let subOrder = 0;
      for (const sub of mid.subs) {
        const [subRow] = await db.insert(qnaCategories).values({
          name: sub.name, slug: sub.slug, parentId: midRow.id, depth: 2,
          sortOrder: subOrder++, isActive: 1,
        }).returning();
        slugToId.set(sub.slug, subRow.id);
      }
    }
  }
  console.log(`[seed-qna] 카테고리 ${slugToId.size}개 생성`);

  // 3) 질문/답변 생성
  let inserted = 0;
  for (const q of SEED_QUESTIONS) {
    const categoryId = slugToId.get(q.categorySlug);
    if (!categoryId) {
      console.warn(`[seed-qna] 카테고리 slug 누락: ${q.categorySlug}`);
      continue;
    }
    const slug = generateQuestionSlug(q.title);
    await db.insert(qnaQuestions).values({
      slug,
      categoryId,
      title: q.title,
      body: q.body,
      displayName: q.displayName,
      anonymityTier: 2,
      answer: q.answer,
      answeredBy: q.answeredBy,
      answeredAt: now,
      status: "published",
      isFeatured: q.isFeatured || 0,
      publishedAt: now,
      createdAt: now,
      updatedAt: now,
    });
    inserted++;
  }
  console.log(`[seed-qna] 질문 ${inserted}개 생성 (공개 상태)`);

  console.log("[seed-qna] 완료");
  process.exit(0);
}

seed().catch((e) => {
  console.error("[seed-qna] 실패:", e);
  process.exit(1);
});
