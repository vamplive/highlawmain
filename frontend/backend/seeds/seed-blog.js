function slug(title) {
  const base = title.toLowerCase().replace(/[^\w가-힣\s-]/g, "").replace(/\s+/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "");
  return `${base}-${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`;
}

